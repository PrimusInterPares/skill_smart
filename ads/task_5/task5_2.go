// Краткое название: функция, 'вращающая' очередь по кругу на N элементов
// Time complexity: O(N)
// Memory complexity: O(N)
func (q *Queue[T]) Rotate(n int) {
	if q.Size() <= 1 || n == 0 {
		return
	}

	normalN := n % q.Size() // 10 / 3 = 1 реальный круг
	if normalN < 0 {
		normalN += q.Size()
	}

	q.items = append(q.items[normalN:], q.items[:normalN]...)
}

